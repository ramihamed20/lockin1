#!/usr/bin/env python3
"""Atomic, conflict-guarded rollback for Physiology All-Questions import.

Dry-run by default; requires `--apply` and a valid SHA-256 verified snapshot
generated by `predeploy_check_and_backup_physiology.py` prior to import.

Safety guarantees:
  1. Verifies snapshot (and optional post-import manifest) SHA-256 integrity.
  2. Identifies newly imported normal questions strictly by `import_batch_id`
     (never by `created_at` heuristics).
  3. Aborts atomically with `RollbackConflictError` if any post-import edits,
     additional batches, or student activity occurred after the target import.
  4. Fully restores or recreates deleted `ActiveStudyQuestionContent`,
     `ActiveStudySettings`, and backed-up `Question`/`QuestionVersion`/
     `QuestionOption`/`QuestionImportBatch` records.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Any


class RollbackConflictError(ValueError):
    """Raised when post-import DB drift or ambiguity makes rollback unsafe."""


def _canonical_sha256(obj: Any) -> str:
    raw = json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def verify_snapshot_envelope(envelope: dict[str, Any]) -> dict[str, Any]:
    """Verify snapshot SHA-256 digest and return the inner snapshot dict."""

    expected_sha = envelope.get("snapshot_sha256")
    snapshot = envelope.get("snapshot")
    if (
        not isinstance(expected_sha, str)
        or not isinstance(snapshot, dict)
        or _canonical_sha256(snapshot) != expected_sha
    ):
        raise ValueError("Snapshot SHA-256 verification failed; refusing rollback.")
    return snapshot


def verify_postimport_manifest(
    manifest_envelope: dict[str, Any],
    snapshot_sha256: str,
) -> dict[str, Any]:
    """Verify post-import manifest SHA-256 and link to the pre-deploy snapshot."""

    expected_sha = manifest_envelope.get("manifest_sha256")
    manifest = manifest_envelope.get("manifest")
    if (
        not isinstance(expected_sha, str)
        or not isinstance(manifest, dict)
        or _canonical_sha256(manifest) != expected_sha
    ):
        raise ValueError("Post-import manifest SHA-256 verification failed; refusing rollback.")
    if manifest.get("snapshot_sha256") != snapshot_sha256:
        raise RollbackConflictError(
            "Post-import manifest belongs to a different pre-deploy snapshot."
        )
    return manifest


def _parse_dt(value: str | None) -> datetime | None:
    return datetime.fromisoformat(value) if value else None


def _resolve_target_batch(
    *,
    sheet_id: str,
    cur_batches: list[Any],
    baseline_batch_ids: set[str],
    has_explicit_batch: bool,
    explicit_batch_id: str | None,
) -> Any | None:
    """Resolve the single target QuestionImportBatch strictly by batch ID."""

    new_batches = [b for b in cur_batches if str(b.id) not in baseline_batch_ids]
    if has_explicit_batch:
        if explicit_batch_id is None:
            if new_batches:
                raise RollbackConflictError(
                    f"Sheet {sheet_id}: expected 0 new import batches, found {len(new_batches)}."
                )
            return None
        matches = [b for b in cur_batches if str(b.id) == explicit_batch_id]
        if not matches:
            raise RollbackConflictError(
                f"Sheet {sheet_id}: target import batch {explicit_batch_id} not found."
            )
        extra_new = [b for b in new_batches if str(b.id) != explicit_batch_id]
        if extra_new:
            raise RollbackConflictError(
                f"Sheet {sheet_id}: {len(extra_new)} additional import batch(es) exist beyond target batch {explicit_batch_id}."
            )
        return matches[0]

    if len(new_batches) > 1:
        raise RollbackConflictError(
            f"Sheet {sheet_id}: {len(new_batches)} import batches created after snapshot; refusing ambiguous rollback."
        )
    return new_batches[0] if new_batches else None


def _recreate_question_from_backup(
    prev_q: dict[str, Any],
    *,
    QuestionImportBatch: Any,
    Question: Any,
    QuestionVersion: Any,
    QuestionOption: Any,
) -> None:
    """Recreate a deleted backed-up Question and its versions, options, and batch."""

    batch_id = prev_q.get("import_batch_id")
    batch_data = prev_q.get("import_batch")
    if batch_id and not QuestionImportBatch.objects.filter(id=batch_id).exists():
        if not isinstance(batch_data, dict):
            raise RollbackConflictError(
                f"Cannot recreate deleted question {prev_q['id']} without import_batch metadata."
            )
        QuestionImportBatch.objects.create(
            id=batch_data["id"],
            actor_id=batch_data["actor_id"],
            academic_node_id=batch_data["academic_node_id"],
            sheet_id=batch_data["sheet_id"],
            schema_version=batch_data["schema_version"],
            status=batch_data["status"],
            question_count=batch_data["question_count"],
            type_counts=batch_data["type_counts"],
            warnings=batch_data["warnings"],
            undone_by_id=batch_data["undone_by_id"],
            undone_at=_parse_dt(batch_data["undone_at"]),
        )

    question = Question.objects.create(
        id=prev_q["id"],
        owner_id=prev_q["owner_id"],
        import_batch_id=batch_id,
        current_version=None,
        published_version=None,
        workflow_status=prev_q["workflow_status"],
        review_note=prev_q.get("review_note", ""),
        revision=prev_q["revision"],
        published_at=_parse_dt(prev_q["published_at"]),
        retired_at=_parse_dt(prev_q["retired_at"]),
    )
    for ver in prev_q["versions"]:
        ver_obj = QuestionVersion.objects.create(
            id=ver["id"],
            question=question,
            version_number=ver["version_number"],
            academic_node_id=ver["academic_node_id"],
            source_learning_object_id=ver["source_learning_object_id"],
            question_type=ver["question_type"],
            prompt=ver["prompt"],
            explanation=ver["explanation"],
            topic=ver["topic"],
            source_page=ver["source_page"],
            difficulty=ver["difficulty"],
            language=ver["language"],
            metadata=ver["metadata"],
            created_by_id=ver["created_by_id"],
        )
        for opt in ver["options"]:
            QuestionOption.objects.create(
                id=opt["id"],
                version=ver_obj,
                text=opt["text"],
                position=opt["position"],
                is_correct=opt["is_correct"],
            )
    question.current_version_id = prev_q["current_version_id"]
    question.published_version_id = prev_q["published_version_id"]
    question.save(update_fields=("current_version_id", "published_version_id"))


def rollback_from_snapshot(
    envelope: dict[str, Any],
    *,
    apply: bool = False,
    target_batch_ids: dict[str, str | None] | None = None,
    post_import_manifest: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Verify integrity, guard against post-import drift, and roll back atomically."""

    from django.db import transaction
    from django.utils import timezone
    from apps.content.all_questions import ALL_QUESTIONS_ORIGIN_KEY, ALL_QUESTIONS_ORIGIN_VALUE
    from apps.content.models import (
        ActiveStudyQuestionContent,
        ActiveStudySettings,
        LearningObject,
    )
    from apps.focus.models import ActiveStudyRun
    from apps.questions.models import (
        Question,
        QuestionAnswer,
        QuestionImportBatch,
        QuestionOption,
        QuestionVersion,
    )

    snapshot = verify_snapshot_envelope(envelope)
    manifest: dict[str, Any] | None = None
    if post_import_manifest is not None:
        manifest = verify_postimport_manifest(post_import_manifest, envelope["snapshot_sha256"])

    batch_overrides = target_batch_ids or {}
    actions: list[dict[str, Any]] = []

    with transaction.atomic():
        for entry in snapshot["target_sheets"]:
            if not entry.get("exists"):
                continue
            sid = entry["sheet_id"]
            sheet = LearningObject.objects.select_for_update().get(id=sid)
            pm = (manifest["sheets"].get(sid) if manifest else None) or {}

            prev_content = {row["difficulty"]: row for row in entry["active_study_content_backup"]}
            prev_settings = {row["edition"]: row for row in entry["active_study_settings_backup"]}
            cur_batches = list(
                QuestionImportBatch.objects.select_for_update()
                .filter(sheet=sheet)
                .order_by("created_at", "id")
            )
            cur_contents = list(
                ActiveStudyQuestionContent.objects.select_for_update()
                .filter(sheet=sheet)
                .order_by("difficulty")
            )
            cur_settings = list(
                ActiveStudySettings.objects.select_for_update()
                .filter(sheet=sheet)
                .order_by("edition")
            )

            has_explicit_batch = sid in batch_overrides or "sheet_question_batch_id" in pm
            explicit_batch_id = (
                batch_overrides[sid]
                if sid in batch_overrides
                else pm.get("sheet_question_batch_id")
            )
            target_batch = _resolve_target_batch(
                sheet_id=sid,
                cur_batches=cur_batches,
                baseline_batch_ids=set(entry.get("baseline_import_batch_ids", [])),
                has_explicit_batch=has_explicit_batch,
                explicit_batch_id=explicit_batch_id,
            )

            # 1. Select newly imported questions strictly by import_batch_id
            target_qs: list[Any] = []
            if target_batch is not None:
                if target_batch.status == QuestionImportBatch.Status.UNDONE:
                    raise RollbackConflictError(
                        f"Sheet {sid}: import batch {target_batch.id} was already undone."
                    )
                target_qs = list(
                    Question.objects.select_for_update(of=("self",))
                    .filter(import_batch_id=target_batch.id)
                    .select_related("current_version")
                    .prefetch_related("versions")
                    .order_by("id")
                )
                for q in target_qs:
                    ver = q.current_version
                    if ver is None or str(ver.source_learning_object_id) != sid:
                        raise RollbackConflictError(
                            f"Sheet {sid}: batch {target_batch.id} question {q.id} does not belong to target sheet."
                        )
                    if (ver.metadata or {}).get(ALL_QUESTIONS_ORIGIN_KEY) != ALL_QUESTIONS_ORIGIN_VALUE:
                        raise RollbackConflictError(
                            f"Sheet {sid}: batch {target_batch.id} question {q.id} is not all_questions origin."
                        )

            # 2. Concurrency & post-import modification guard
            if target_qs and QuestionAnswer.objects.filter(question__in=target_qs).exists():
                raise RollbackConflictError(
                    f"Sheet {sid}: students have already answered questions in import batch {target_batch.id}."
                )
            baseline_run_ids = entry.get("baseline_active_study_run_ids", [])
            if ActiveStudyRun.objects.filter(sheet=sheet).exclude(id__in=baseline_run_ids).exists():
                raise RollbackConflictError(
                    f"Sheet {sid}: ActiveStudyRun activity occurred after pre-deploy snapshot."
                )

            if pm:
                cur_settings_revs = {s.edition: s.revision for s in cur_settings}
                if cur_settings_revs != pm["settings_revisions"]:
                    raise RollbackConflictError(
                        f"Sheet {sid}: ActiveStudySettings changed after target import "
                        f"(expected {pm['settings_revisions']}, got {cur_settings_revs})."
                    )
                cur_content_revs = {c.difficulty: c.revision for c in cur_contents}
                if cur_content_revs != pm["content_revisions"]:
                    raise RollbackConflictError(
                        f"Sheet {sid}: ActiveStudyQuestionContent revisions changed after target import "
                        f"(expected {pm['content_revisions']}, got {cur_content_revs})."
                    )
                cur_content_digests = {c.difficulty: _canonical_sha256(c.payload) for c in cur_contents}
                if cur_content_digests != pm["content_payload_sha256"]:
                    raise RollbackConflictError(
                        f"Sheet {sid}: ActiveStudyQuestionContent payload modified after target import."
                    )
                cur_batch_revs = {
                    str(q.id): {"revision": q.revision, "workflow_status": q.workflow_status}
                    for q in target_qs
                }
                if cur_batch_revs != pm["batch_question_revisions"]:
                    raise RollbackConflictError(
                        f"Sheet {sid}: imported questions were modified after target import."
                    )
            else:
                # Baseline structural invariants when no post-import manifest is supplied
                for c in cur_contents:
                    max_expected_rev = (
                        prev_content[c.difficulty]["revision"] + 1
                        if c.difficulty in prev_content
                        else 1
                    )
                    if c.revision > max_expected_rev:
                        raise RollbackConflictError(
                            f"Sheet {sid}: {c.difficulty} bank revision {c.revision} exceeds single-import maximum {max_expected_rev}."
                        )
                    if target_batch is not None and c.updated_at > target_batch.created_at:
                        raise RollbackConflictError(
                            f"Sheet {sid}: {c.difficulty} bank was updated after target import batch {target_batch.id}."
                        )
                uni_cur = next((s for s in cur_settings if s.edition == "university"), None)
                if uni_cur is not None:
                    prev_uni_rev = prev_settings["university"]["revision"] if "university" in prev_settings else 0
                    if uni_cur.revision > prev_uni_rev + 2:
                        raise RollbackConflictError(
                            f"Sheet {sid}: ActiveStudySettings revision {uni_cur.revision} indicates multiple post-snapshot changes."
                        )
                    if target_batch is not None and uni_cur.updated_at > target_batch.created_at:
                        raise RollbackConflictError(
                            f"Sheet {sid}: ActiveStudySettings modified after target import batch {target_batch.id}."
                        )
                if target_batch is not None:
                    expected_status = (
                        Question.WorkflowStatus.PUBLISHED
                        if target_batch.status == QuestionImportBatch.Status.PUBLISHED
                        else Question.WorkflowStatus.DRAFT
                    )
                    expected_init_rev = (
                        3 if target_batch.status == QuestionImportBatch.Status.PUBLISHED else 1
                    )
                    for q in target_qs:
                        if (
                            q.workflow_status != expected_status
                            or q.revision > expected_init_rev
                            or len(list(q.versions.all())) > 1
                        ):
                            raise RollbackConflictError(
                                f"Sheet {sid}: imported question {q.id} was modified after import batch {target_batch.id}."
                            )

            # Ensure baseline non-all_questions questions stayed intact & no rogue questions appeared
            untouched_baseline = entry.get("untouched_questions_baseline", {})
            backed_up_ids = {row["id"] for row in entry["will_archive_questions_backup"]}
            target_q_ids = {str(q.id) for q in target_qs}
            cur_sheet_qs = list(
                Question.objects.select_for_update(of=("self",))
                .filter(current_version__source_learning_object=sheet)
                .order_by("id")
            )
            cur_sheet_q_by_id = {str(q.id): q for q in cur_sheet_qs}
            for u_id, expected_u in untouched_baseline.items():
                uq = cur_sheet_q_by_id.get(u_id)
                if uq is None:
                    raise RollbackConflictError(
                        f"Sheet {sid}: untouched baseline question {u_id} went missing."
                    )
                cur_cv = str(uq.current_version_id) if uq.current_version_id else None
                if (
                    uq.workflow_status != expected_u["workflow_status"]
                    or uq.revision != expected_u["revision"]
                    or cur_cv != expected_u["current_version_id"]
                ):
                    raise RollbackConflictError(
                        f"Sheet {sid}: baseline question {u_id} changed concurrently."
                    )
            known_ids = backed_up_ids | set(untouched_baseline.keys()) | target_q_ids
            rogue_ids = sorted(set(cur_sheet_q_by_id.keys()) - known_ids)
            if rogue_ids:
                raise RollbackConflictError(
                    f"Sheet {sid}: unexpected question(s) added outside target import batch: {rogue_ids[:5]}"
                )

            # Check backed-up questions weren't edited beyond single archive
            for prev_q in entry["will_archive_questions_backup"]:
                existing_q = (
                    Question.objects.select_for_update(of=("self",)).filter(id=prev_q["id"]).first()
                )
                if existing_q is not None and existing_q.revision > prev_q["revision"] + 1:
                    raise RollbackConflictError(
                        f"Sheet {sid}: previously archived question {prev_q['id']} was modified after import."
                    )

            # 3. Restore ActiveStudyQuestionContent (update existing, delete new, recreate deleted)
            seen_diffs: set[str] = set()
            deleted_banks: list[str] = []
            restored_banks: list[str] = []
            recreated_banks: list[str] = []
            for cur in cur_contents:
                if cur.difficulty not in prev_content:
                    deleted_banks.append(cur.difficulty)
                    if apply:
                        cur.delete()
                else:
                    seen_diffs.add(cur.difficulty)
                    old = prev_content[cur.difficulty]
                    restored_banks.append(cur.difficulty)
                    if apply:
                        cur.payload = old["payload"]
                        cur.plan_signature = old["plan_signature"]
                        cur.source_version_id = old["source_version_id"]
                        cur.checkpoint_question_count = old["checkpoint_question_count"]
                        cur.final_exam_question_count = old["final_exam_question_count"]
                        cur.revision = old["revision"]
                        cur.created_by_id = old["created_by_id"]
                        cur.updated_by_id = old["updated_by_id"]
                        cur.save(
                            update_fields=(
                                "payload",
                                "plan_signature",
                                "source_version_id",
                                "checkpoint_question_count",
                                "final_exam_question_count",
                                "revision",
                                "created_by_id",
                                "updated_by_id",
                            )
                        )
            for diff, old in prev_content.items():
                if diff not in seen_diffs:
                    recreated_banks.append(diff)
                    if apply:
                        ActiveStudyQuestionContent.objects.create(
                            sheet=sheet,
                            difficulty=diff,
                            payload=old["payload"],
                            plan_signature=old["plan_signature"],
                            source_version_id=old["source_version_id"],
                            checkpoint_question_count=old["checkpoint_question_count"],
                            final_exam_question_count=old["final_exam_question_count"],
                            revision=old["revision"],
                            created_by_id=old["created_by_id"],
                            updated_by_id=old["updated_by_id"],
                        )

            # 4. Restore ActiveStudySettings (update existing, delete new, recreate deleted)
            seen_editions: set[str] = set()
            settings_ops: list[str] = []
            for s in cur_settings:
                if s.edition not in prev_settings:
                    settings_ops.append(f"delete:{s.edition}")
                    if apply:
                        s.delete()
                else:
                    seen_editions.add(s.edition)
                    old = prev_settings[s.edition]
                    settings_ops.append(f"restore:{s.edition}:rev{old['revision']}")
                    if apply:
                        s.enabled = old["enabled"]
                        s.total_pdf_pages = old["total_pdf_pages"]
                        s.source_version_id = old["source_version_id"]
                        s.page_count_verified_at = _parse_dt(old.get("page_count_verified_at"))
                        s.excluded_start_pages = old["excluded_start_pages"]
                        s.excluded_end_pages = old["excluded_end_pages"]
                        s.questions_per_checkpoint = old["questions_per_checkpoint"]
                        s.final_exam_questions = old["final_exam_questions"]
                        s.revision = old["revision"]
                        s.save(
                            update_fields=(
                                "enabled",
                                "total_pdf_pages",
                                "source_version_id",
                                "page_count_verified_at",
                                "excluded_start_pages",
                                "excluded_end_pages",
                                "questions_per_checkpoint",
                                "final_exam_questions",
                                "revision",
                            )
                        )
            for edition, old in prev_settings.items():
                if edition not in seen_editions:
                    settings_ops.append(f"recreate:{edition}:rev{old['revision']}")
                    if apply:
                        ActiveStudySettings.objects.create(
                            sheet=sheet,
                            edition=edition,
                            enabled=old["enabled"],
                            total_pdf_pages=old["total_pdf_pages"],
                            source_version_id=old["source_version_id"],
                            page_count_verified_at=_parse_dt(old.get("page_count_verified_at")),
                            excluded_start_pages=old["excluded_start_pages"],
                            excluded_end_pages=old["excluded_end_pages"],
                            questions_per_checkpoint=old["questions_per_checkpoint"],
                            final_exam_questions=old["final_exam_questions"],
                            revision=old["revision"],
                        )

            # 5. Soft-retire target batch questions identified strictly by import_batch_id
            now = timezone.now()
            retired_new_count = 0
            if target_batch is not None:
                for q in target_qs:
                    if q.workflow_status != Question.WorkflowStatus.RETIRED:
                        retired_new_count += 1
                        if apply:
                            q.workflow_status = Question.WorkflowStatus.RETIRED
                            q.retired_at = now
                            q.revision += 1
                            q.save(update_fields=("workflow_status", "retired_at", "revision"))
                if apply:
                    target_batch.status = QuestionImportBatch.Status.UNDONE
                    target_batch.undone_at = now
                    target_batch.save(update_fields=("status", "undone_at"))

            # 6. Restore or recreate backed-up questions (even if deleted during import)
            restored_prev_qs = 0
            recreated_prev_qs = 0
            for prev_q in entry["will_archive_questions_backup"]:
                q = Question.objects.select_for_update().filter(id=prev_q["id"]).first()
                if q is None:
                    recreated_prev_qs += 1
                    if apply:
                        _recreate_question_from_backup(
                            prev_q,
                            QuestionImportBatch=QuestionImportBatch,
                            Question=Question,
                            QuestionVersion=QuestionVersion,
                            QuestionOption=QuestionOption,
                        )
                    continue

                if (
                    q.workflow_status != prev_q["workflow_status"]
                    or q.revision != prev_q["revision"]
                    or str(q.current_version_id or "") != (prev_q["current_version_id"] or "")
                    or str(q.published_version_id or "") != (prev_q["published_version_id"] or "")
                ):
                    restored_prev_qs += 1
                    if apply:
                        q.workflow_status = prev_q["workflow_status"]
                        q.retired_at = _parse_dt(prev_q["retired_at"])
                        q.published_at = _parse_dt(prev_q["published_at"])
                        q.revision = prev_q["revision"]
                        q.review_note = prev_q.get("review_note", "")
                        q.current_version_id = prev_q["current_version_id"]
                        q.published_version_id = prev_q["published_version_id"]
                        q.save(
                            update_fields=(
                                "workflow_status",
                                "retired_at",
                                "published_at",
                                "revision",
                                "review_note",
                                "current_version_id",
                                "published_version_id",
                            )
                        )
                prev_batch = prev_q.get("import_batch")
                if prev_batch and apply:
                    b_obj = QuestionImportBatch.objects.select_for_update().filter(id=prev_batch["id"]).first()
                    if b_obj is not None and b_obj.status != prev_batch["status"]:
                        b_obj.status = prev_batch["status"]
                        b_obj.undone_by_id = prev_batch["undone_by_id"]
                        b_obj.undone_at = _parse_dt(prev_batch["undone_at"])
                        b_obj.save(update_fields=("status", "undone_by_id", "undone_at"))

            actions.append(
                {
                    "sheet_id": sid,
                    "label": entry["label"],
                    "applied": apply,
                    "target_import_batch_id": str(target_batch.id) if target_batch else None,
                    "deleted_new_banks": deleted_banks,
                    "restored_prev_banks": restored_banks,
                    "recreated_deleted_banks": recreated_banks,
                    "settings_ops": settings_ops,
                    "retired_newly_imported_questions": retired_new_count,
                    "restored_previously_archived_questions": restored_prev_qs,
                    "recreated_deleted_questions": recreated_prev_qs,
                }
            )
        if not apply:
            transaction.set_rollback(True)

    return {"applied": apply, "actions": actions}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot_json", type=Path)
    parser.add_argument(
        "--post-import-manifest",
        type=Path,
        default=None,
        help="Optional post-import manifest JSON for strict expected-state verification.",
    )
    parser.add_argument(
        "--batch-id",
        action="append",
        default=[],
        help="Explicit target import batch mapping <sheet_id>=<batch_uuid> (repeatable).",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Commit rollback changes; default is dry-run.",
    )
    args = parser.parse_args()

    os.environ.setdefault(
        "DJANGO_SETTINGS_MODULE",
        os.environ.get("DJANGO_SETTINGS_MODULE", "config.settings.production"),
    )
    import django

    django.setup()
    envelope = json.loads(args.snapshot_json.read_text(encoding="utf-8"))
    manifest = (
        json.loads(args.post_import_manifest.read_text(encoding="utf-8"))
        if args.post_import_manifest
        else None
    )
    overrides: dict[str, str | None] = {}
    for item in args.batch_id:
        sheet_id, batch_val = item.split("=", 1)
        overrides[sheet_id] = None if batch_val == "none" else batch_val

    report = rollback_from_snapshot(
        envelope,
        apply=args.apply,
        target_batch_ids=overrides or None,
        post_import_manifest=manifest,
    )
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


