export function normalizeLocale(value) {
  const candidate = String(value || "").toLowerCase().split(/[-_]/)[0];
  return SUPPORTED_LOCALES.includes(candidate) ? candidate : "en";
}

export function directionForLocale(locale) {
  return normalizeLocale(locale) === "ar" ? "rtl" : "ltr";
}

/**
 * Picks the variant of a key that matches the count being described.
 *
 * English has two count forms and Arabic has six, so a counted phrase cannot be
 * one string with a number dropped into it. A key may instead be written as a
 * set of variants - "materials.sheetCount.one", ".two", ".few", ".many",
 * ".other" - and the right one is chosen from the `count` variable. Keys
 * written as a single string are unaffected.
 */
function pluralTemplate(catalog, key, variables, locale) {
  if (typeof variables.count !== "number" || !Number.isFinite(variables.count)) return undefined;
  const category = pluralCategory(variables.count, locale);
  return catalog[`${key}.${category}`] ?? catalog[`${key}.other`];
}

export function translate(locale, key, variables = {}) {
  const normalized = normalizeLocale(locale);
  const catalog = messages[normalized] || messages.en;
  const template = pluralTemplate(catalog, key, variables, normalized)
    ?? catalog[key]
    ?? pluralTemplate(messages.en, key, variables, "en")
    ?? messages.en[key]
    ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => {
    const value = variables[name];
    if (value === undefined || value === null) return `{${name}}`;
    // Arabic reads its own digits, and a count is the one number that always
    // appears inside a sentence rather than beside one.
    return name === "count" && typeof value === "number" ? formatNumber(value, {}, normalized) : value;
  });
}

export function currentAppLocale() {
  if (typeof document === "undefined") return "en";
  return normalizeLocale(document.documentElement.lang);
}

function intlLocale(locale) {
  return normalizeLocale(locale) === "ar" ? "ar-u-nu-arab" : "en";
}

function validDate(value) {
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

export function formatDate(value, options = {}, locale = currentAppLocale()) {
  const date = validDate(value);
  return date ? new Intl.DateTimeFormat(intlLocale(locale), options).format(date) : "—";
}

export function formatDateTime(value, options = {}, locale = currentAppLocale()) {
  return formatDate(value, {
    dateStyle: "medium",
    timeStyle: "short",
    ...options
  }, locale);
}

export function formatTime(value, options = {}, locale = currentAppLocale()) {
  return formatDate(value, { hour: "numeric", minute: "2-digit", ...options }, locale);
}

export function formatNumber(value, options = {}, locale = currentAppLocale()) {
  const number = Number(value);
  return Number.isFinite(number) ? new Intl.NumberFormat(intlLocale(locale), options).format(number) : "—";
}

export function formatRelativeTime(value, unit, locale = currentAppLocale()) {
  const number = Number(value);
  return Number.isFinite(number)
    ? new Intl.RelativeTimeFormat(intlLocale(locale), { numeric: "auto" }).format(number, unit)
    : "—";
}

export function pluralCategory(value, locale = currentAppLocale()) {
  return new Intl.PluralRules(intlLocale(locale)).select(Number(value) || 0);
}

export function greetingKey(date = new Date()) {
  const hour = date.getHours();
  if (hour < 12) return "greeting.morning";
  if (hour < 18) return "greeting.afternoon";
  return "greeting.evening";
}

export function messageCatalog(locale) {
  return { ...messages.en, ...(messages[normalizeLocale(locale)] || {}) };
}
